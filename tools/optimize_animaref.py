"""Pack the installed Animaref sheets smaller for phones (never touches the idle).

Run AFTER tools/install_animaref.py (which restores the full-size sheets).
1. Lossless: crop every sheet to the union of the non-transparent pixels of
   its 36 frames (+1 px). The picture does not change, only empty margins go.
2. Soften: resample by a per-clip factor (premultiplied alpha, Lanczos).
The runtime (animaref_clips.gd, PACK) maps the crop/scale back onto the same
virtual canvas, so placement, timing and registration stay as installed.
Writes game/scripts/ui/animaref_pack.gd. Idle sheet is not read or written.
"""
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'game/assets/sprites/characters/tiro_pet_puppy_animaref'
CLIPS_GD = ROOT / 'game/scripts/ui/animaref_clips.gd'
OUT_GD = ROOT / 'game/scripts/ui/animaref_pack.gd'
# Eating clips were already drawn ~1.5x bigger on screen, so they keep more.
# Exact ratios (numerator, denominator): the crop is padded to a multiple of the
# denominator so the scale is identical on both axes and the aspect never drifts.
SCALE = {'eat_enter': (4, 5), 'eat_loop': (4, 5), 'eat_exit': (4, 5)}
DEFAULT_SCALE = (3, 4)
PAGED = ('bath', 'play_ball')


def layouts():
    text = CLIPS_GD.read_text(encoding='utf-8')
    block = text[text.index('const LAYOUTS'):text.index('const EXIT_MARGINS')]
    return {m.group(1): (int(m.group(2)), int(m.group(3)))
            for m in re.finditer(r'&"(\w+)": \[Vector2\((\d+), (\d+)\)', block)}


def sheets(clip):
    if clip in PAGED:
        return [TARGET / f'{clip}_0.png', TARGET / f'{clip}_1.png']
    return [TARGET / f'{clip}.png']


def main():
    lines = ['extends RefCounted',
             '## Generated by tools/optimize_animaref.py - crop (lossless) + scale of the sheets.',
             '## crop: union rectangle kept from each original frame; cell: new cell size;',
             '## scale: new px per original px. animaref_clips.gd maps it back to the same canvas.',
             'const PACK := {']
    before = after = 0
    for clip, (w, h) in layouts().items():
        if clip == 'idle_breathe':
            continue  # locked by Vitor: never rewritten
        columns = 3 if clip == 'play_ball' else 6
        images = [Image.open(p).convert('RGBA') for p in sheets(clip)]
        if any(im.size[0] % w or im.size[1] % h for im in images):
            raise SystemExit(f'{clip}: sheet is not the original size; run install_animaref.py first')
        box = None
        for im in images:
            alpha = im.getchannel('A')
            for row in range(im.size[1] // h):
                for col in range(im.size[0] // w):
                    b = alpha.crop((col*w, row*h, (col+1)*w, (row+1)*h)).getbbox()
                    if b:
                        box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
        num, den = SCALE.get(clip, DEFAULT_SCALE)
        factor = num / den
        x0, y0 = box[0]-1, box[1]-1
        bw, bh = box[2]+1-x0, box[3]+1-y0
        # pad (transparent) up to a multiple of den, centered on the picture
        extra_w, extra_h = -bw % den, -bh % den
        x0, y0 = x0 - extra_w//2, y0 - extra_h//2
        bw, bh = bw + extra_w, bh + extra_h
        nw, nh = bw*num//den, bh*num//den
        for path, im in zip(sheets(clip), images):
            before += path.stat().st_size
            cols = im.size[0] // w if clip not in PAGED else columns
            rows = im.size[1] // h
            sheet = Image.new('RGBA', (cols*nw, rows*nh))
            for row in range(rows):
                for col in range(cols):
                    cell = im.crop((col*w, row*h, (col+1)*w, (row+1)*h)).crop((x0, y0, x0+bw, y0+bh))
                    small = cell.convert('RGBa').resize((nw, nh), Image.LANCZOS).convert('RGBA')
                    # Lanczos leaves a faint ringing halo; cut it so silhouettes keep their edges.
                    alpha = small.getchannel('A').point(lambda a: 0 if a < 6 else a)
                    small.putalpha(alpha)
                    sheet.paste(small, (col*nw, row*nh))
            sheet.save(path, optimize=True)
            after += path.stat().st_size
        lines.append(f'\t&"{clip}": {{"crop": Rect2({x0}, {y0}, {bw}, {bh}), "cell": Vector2({nw}, {nh}), "scale": Vector2({factor:.6f}, {factor:.6f})}},')
        print(f'{clip}: {w}x{h} -> crop {bw}x{bh} -> cell {nw}x{nh}')
    lines.append('}')
    OUT_GD.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'PNG {before/1e6:.1f} MB -> {after/1e6:.1f} MB')


main()
